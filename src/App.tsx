import { useState } from 'react'
import ProductCard from './components/ProductCard'
import { products } from './data/products'
import type { CartData } from './interface/Products'
import { getItemsInCart, getTotalInCart } from './functions/carts'
import Cart from './components/Cart'
import { ShoppingCartIcon } from '@phosphor-icons/react'

function App() {
	const [cart, setCart] = useState<CartData[]>([])
	const [showCart, setShowCart] = useState<boolean>(false)

	function handleCartItemAmountChange(productId: number, amount: number) {
		setCart((prev) => {
			const existingItem = prev.find(
				(item) => item.product.id === productId
			);

			if (!existingItem) return prev;

			if (existingItem.amount + amount <= 0) {
				return prev.filter(
					(item) => item.product.id !== productId
				);
			}

			return prev.map((item) =>
				item.product.id === productId
					? { ...item, amount: item.amount + amount }
					: item
			);
		});
	}

	function handleCartItemAmountSet(productId: number, amount: number) {
		// If user types anything <= 0
		if (amount <= 0) {
			handleCartItemDelete(productId);
			return;
		}

		setCart((prev) =>
			prev.map((item) =>
				item.product.id === productId
					? { ...item, amount }
					: item
			)
		);
	}

	function handleCartItemDelete(productId: number) {
		setCart((prev) =>
			prev.filter((item) =>
				item.product.id !== productId
			)
		)
	}

	function handleCheckout() {
		alert(`The food has been ordered!\nThe total price is ${getTotalInCart(cart)} ฿.`)
		setCart([])
	}

	return (
		<div className='relative min-h-screen p-8 flex flex-col gap-12 lg:px-[10vw] xl:px-[12vw]'>
			{/* Cart */}
			<Cart
				cart={cart}
				showCart={showCart}
				setShowCart={setShowCart}
				handleCartItemAmountChange={handleCartItemAmountChange}
				handleCartItemAmountSet={handleCartItemAmountSet}
				handleCartItemDelete={handleCartItemDelete}
				handleCheckout={handleCheckout}
			/>

			<div className='flex items-center justify-between gap-4 mt-2'>
				<h1 className='text-3xl font-bold text-wrap'>Computer food</h1>
				<div
					onClick={() => { setShowCart(true) }}
					className={`${showCart && "hidden"} fixed bottom-8 right-8 z-100 bg-white flex items-center gap-3 border border-gray-200 rounded-full p-6 shadow-md group hover:bg-pink-400 hover:border-transparent transition-all duration-100 cursor-pointer`}>
					{cart.length > 0 && (
						<div className='min-w-8 bg-pink-400 text-white rounded-full border group-hover:border-white/25 px-2 py-1'>
							<p className='text-center text-md font-bold'>{getItemsInCart(cart)}</p>
						</div>

					)}
					<ShoppingCartIcon
						size={42} weight="duotone"
						className="opacity-50 group-hover:text-white group-hover:opacity-100"
					/>
				</div>
			</div>

			<div className='grid sm:grid-cols-2 md:grid-cols-3 lg:grid-cols-4 xl:grid-cols-5 gap-4'>
				{products.map((product) => (
					<ProductCard
						key={product.id}
						product={product}
						cart={cart}
						setCart={setCart} />
				))}
			</div>

			<footer className='border border-gray-200 rounded-2xl p-6 mt-auto flex flex-col gap-4'>
				<p className='text-xl font-bold'>1-68-070-675-9 · Nawee Moongmart</p>
				<em className='opacity-50'>Menu entries and images are generated by artificial intelligence.</em>
			</footer>
		</div>
	)
}

export default App
